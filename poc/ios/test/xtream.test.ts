import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { parseAccount, parseLiveStreams, parseCategories, chooseFormat, liveUrl, normalizeServer } from '../src/xtream.ts';
import { redact } from '../src/redact.ts';
const F = new URL('../../../contracts/fixtures/xtream/', import.meta.url).pathname;
const j = (f: string) => JSON.parse(readFileSync(F + f, 'utf8'));
const acc = parseAccount(j('player_api_login.json'));
assert.deepEqual(acc.allowedFormats, ['m3u8', 'ts']); assert.equal(acc.maxConnections, 2);
assert.throws(() => parseAccount(j('player_api_login_unauthorized.json')));
const ch = parseLiveStreams(j('get_live_streams.json'));
assert.equal(ch.length, 2); assert.equal(ch[1].streamId, '1002'); assert.equal(ch[1].hasArchive, true); assert.equal(ch[1].epgChannelId, null);
assert.equal(parseCategories(j('get_live_categories.json')).length, 2);
assert.equal(chooseFormat('auto', acc), 'ts');
assert.equal(chooseFormat('auto', { ...acc, allowedFormats: ['m3u8'] }), 'm3u8');
assert.equal(normalizeServer('iptv.example.test:8080/'), 'http://iptv.example.test:8080');
const c = { server: 'iptv.example.test', username: 'demo_user', password: 'demo_pass' };
const u = liveUrl(c, '1001', 'ts');
assert.equal(u, 'http://iptv.example.test/live/demo_user/demo_pass/1001.ts');
assert.equal(redact(u), 'http://iptv.example.test/live/***/***/1001.ts');
assert.equal(redact('http://x.test/player_api.php?username=demo_user&password=demo_pass&action=a'), 'http://x.test/player_api.php?username=***&password=***&action=a');
assert.equal(redact('error en demo_pass', ['demo_pass']), 'error en ***');
console.log('xtream/redact: todas las pruebas OK');
